// Generates data/directory/stats.json — the static dispatch-stats file the
// directory pages read at build time.
//
// TODAY these numbers are deterministic estimates seeded from population
// (placeholders). WHEN REAL DATA IS AVAILABLE: replace this script's formulas
// with an export from the dispatch database and re-run on a daily/weekly
// schedule, keeping the same JSON shape. Pages rebuild from the file.
//
// Run: node scripts/build-directory-stats.mjs
import fs from 'fs'
import path from 'path'
import url from 'url'

const __dirname = path.dirname(url.fileURLToPath(import.meta.url))
const DATA_DIR = path.join(__dirname, '..', 'data', 'directory')
const cities = JSON.parse(fs.readFileSync(path.join(DATA_DIR, 'cities.json'), 'utf8'))
const corridors = JSON.parse(fs.readFileSync(path.join(DATA_DIR, 'corridors.json'), 'utf8'))

// small deterministic hash → 0..1, so numbers vary city-to-city but never
// change between runs (no random build diffs)
function seed01(s) {
  let h = 2166136261
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return ((h >>> 0) % 1000) / 1000
}
const clamp = (n, lo, hi) => Math.max(lo, Math.min(hi, n))

const stats = {
  _note:
    'PLACEHOLDER estimates generated by scripts/build-directory-stats.mjs. Replace generation with a real dispatch-DB export (same shape) before launch; refresh daily/weekly.',
  _generatedFrom: 'population-seeded formulas',
  national: {
    mechanicsNetwork: 6000,
    mechanicsCompletedJobs: 1500,
    avgDispatchMin: 14,
    avgArrivalMin: 47,
    avgCostUsd: 465,
    costVsIndustryPct: -29,
    // % of jobs fixed on site (no tow) — replace with the real network-wide
    // ServiceRating.isFixed aggregate; drives the "don't tow" copy
    fixRatePct: 93,
  },
  states: {},
  cities: {},
  corridors: {},
}

for (const c of cities) {
  const key = `${c.state}/${c.citySlug}`
  const r = seed01(key)
  const pop = Math.max(c.population, 3000)
  // Counts vary LESS than you'd expect from population: mechanics serve a
  // radius, so small towns draw on mechanics based farther out. Time to
  // arrive varies MORE — it's mostly a function of that drive distance.
  const mechanicsInArea = clamp(Math.round(8 + 11 * Math.log10(pop / 1000) + r * 4), 8, 52)
  const avgArrivalMin = clamp(Math.round(102 - 11 * Math.log10(pop) + r * 14), 30, 95)
  const avgDispatchMin = clamp(Math.round(12 + r * 6), 12, 18)
  const jobsCompleted = Math.max(20, Math.round((c.population / 1000) * (0.7 + r * 0.6) / 10) * 10)
  stats.cities[key] = { mechanicsInArea, avgArrivalMin, avgDispatchMin, jobsCompleted }

  const st = (stats.states[c.state] = stats.states[c.state] || {
    mechanicsInArea: 0,
    jobsCompleted: 0,
    _arrSum: 0,
    _n: 0,
  })
  st.mechanicsInArea += mechanicsInArea
  st.jobsCompleted += jobsCompleted
  st._arrSum += avgArrivalMin
  st._n++
}

for (const [code, st] of Object.entries(stats.states)) {
  stats.states[code] = {
    mechanicsInArea: st.mechanicsInArea,
    jobsCompleted: st.jobsCompleted,
    avgArrivalMin: Math.round(st._arrSum / st._n),
    avgDispatchMin: 14,
  }
}

for (const c of corridors) {
  const key = `${c.route}/${c.state}`
  const r = seed01(key)
  stats.corridors[key] = {
    mechanicsCovering: clamp(Math.round(5 + r * 9), 5, 14),
    avgReachMin: clamp(Math.round(48 + r * 34), 48, 82),
  }
}

fs.writeFileSync(path.join(DATA_DIR, 'stats.json'), JSON.stringify(stats, null, 1) + '\n')
console.log(
  `stats.json: ${Object.keys(stats.cities).length} cities, ${Object.keys(stats.states).length} states, ${Object.keys(stats.corridors).length} corridors`
)
